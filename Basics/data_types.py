# int

k=42
print(k)
print(type(k))

big=1_00_00_000    # _ are used for readability purpose.
print(big)
print(type(big))

# for negative values

neg=-17
print(neg)
print(type(neg))      # since it's a negative value still it's an integer

# for binary numbers

bin=0b1010
print(bin)
print(type(bin))




# for octal values

oct=0o17
print(oct)
print(type(oct))


# for hex decimal valus

hex=0xFF
print(hex)
print(type(hex))





