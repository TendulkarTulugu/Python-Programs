# escape sequence

# 1 Tab 
Tab="Name:\tTendul"
print(Tab)

#2 New Line
newl="Line1\nLine2"
print(newl)

# 3 To print text like file path simply to print single slash
singles="C:\\Path\\folder"
print(singles)

# 4 Literal Quotes \"
quot="she said\"HI\""
print(quot)



# The 'r' tells Python to ignore the backslashes inside
path = r"C:\Users\Alice\Documents" 
print(path)


# Highly useful for regex patterns where backslashes are common
x = r"\d+\.\d+"
print(x)